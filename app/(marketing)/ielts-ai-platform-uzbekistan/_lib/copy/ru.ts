/**
 * The noun after a number, in the form Russian needs for it (1 проверка,
 * 2 проверки, 5 проверок). ⚠️ The numbers come from PLAN_TIERS, so the form
 * cannot be typed next to them: the day a limit moves from 5 to 2, a fixed
 * "проверок" would turn ungrammatical without anyone touching this file.
 */
const RULES = new Intl.PluralRules("ru");
const count = (n: number | null, one: string, few: string, many: string) => {
  const form = RULES.select(n ?? 0);
  return `${n} ${form === "one" ? one : form === "few" ? few : many}`;
};

const months = (n: number) => count(n, "месяц", "месяца", "месяцев");
const price = (t: PlanTier) =>
  t.price === null ? "По договорённости" : t.price === 0 ? `$${t.price}` : t.months === 1 ? `$${t.price} в месяц` : `$${t.price} за ${months(t.months)}`;
const perMonth = (n: number | null) => (n === null ? "без ограничений" : `${n} в месяц`);
const library = (t: PlanTier) => (t.libraryLimit === null ? "без ограничений" : count(t.libraryLimit, "задание", "задания", "заданий"));

